def create_pair(client):
    project = client.post("/api/projects", json={"name": "Контрольное сравнение"}).json()
    for phase, text in (("before", BEFORE), ("after", AFTER)):
        response = client.post(
            f"/api/projects/{project['id']}/documents",
            data={"phase": phase},
            files={"file": (f"{phase}.txt", text.encode("utf-8"), "text/plain")},
        )
        assert response.status_code == 201
    return client.get(f"/api/projects/{project['id']}").json()
